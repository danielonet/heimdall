#!/usr/bin/env bash
# setup.sh — first-run setup for a Heimdall release bundle.
#
# Ships inside heimdall-bundle.tar.gz (built by scripts/make-bundle.sh) and is
# run by the website installer (https://heimdall.it.com/install.sh) right
# after unpacking. It can also be run by hand from the unpacked directory.
#
# What it does (safe to re-run — never overwrites an existing .env or secret):
#   1. creates secrets/ with fresh random passwords for this machine
#   2. detects the LAN interface and subnet (override with --iface/--subnet)
#   3. writes .env: tier, compose profiles, registry + image tag, network
#
# It runs non-interactively (the installer gives it no terminal) and needs
# no sudo.
#
# Options: --tier=minimal|intermediate|full  --router=sagemcom|passive
#          --iface=NAME  --subnet=CIDR

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

if [ -t 1 ]; then G=$'\033[32m'; Y=$'\033[33m'; R=$'\033[31m'; B=$'\033[1m'; N=$'\033[0m'; else G=''; Y=''; R=''; B=''; N=''; fi
info() { echo "${B}▸${N} $*"; }
ok()   { echo "${G}✔${N} $*"; }
warn() { echo "${Y}⚠${N} $*" >&2; }
die()  { echo "${R}✖${N} $*" >&2; exit 1; }

TIER="" ROUTER="" IFACE="" SUBNET=""
for arg in "$@"; do
    case "$arg" in
        --tier=*)   TIER="${arg#--tier=}" ;;
        --router=*) ROUTER="${arg#--router=}" ;;
        --iface=*)  IFACE="${arg#--iface=}" ;;
        --subnet=*) SUBNET="${arg#--subnet=}" ;;
        -h|--help)  sed -n '2,18p' "$0"; exit 0 ;;
        *) die "Unknown option: $arg" ;;
    esac
done

case "${TIER:-minimal}" in minimal|intermediate|full) ;; *) die "Invalid --tier=$TIER (minimal, intermediate or full)" ;; esac
case "${ROUTER:-}" in ""|sagemcom|passive) ;; *) die "Invalid --router=$ROUTER (sagemcom or passive)" ;; esac

[ -f VERSION ] || die "VERSION file missing — run this from an unpacked Heimdall bundle"
VERSION="$(tr -d '[:space:]' < VERSION)"
IMAGE_TAG="${VERSION#v}"
REGISTRY="$(tr -d '[:space:]' < REGISTRY 2>/dev/null || true)"
[ -n "$REGISTRY" ] || die "REGISTRY file missing — this bundle was not built by scripts/make-bundle.sh"

# ── 1. Secrets ────────────────────────────────────────────────────────────────
mkdir -p secrets/routers
chmod 700 secrets secrets/routers

# new_secret NAME [CONTENT]  →  random hex if CONTENT is omitted; empty if ""
new_secret() {
    local path="secrets/$1.txt"
    if [ -f "$path" ]; then
        return 0
    fi
    if [ "$#" -ge 2 ]; then printf '%s' "$2" > "$path"; else openssl rand -hex 32 > "$path"; fi
    chmod 600 "$path"
    ok "Created $path"
}

command -v openssl >/dev/null || die "openssl is required to generate secrets"
new_secret jwt_secret
new_secret db_pass
new_secret admin_password
new_secret router_password "CHANGE_ME_router_password"
new_secret otx_api_key "CHANGE_ME_otx_api_key"
new_secret abusech_auth_key ""
new_secret smtp_password ""
new_secret miwifi_password ""

# ── 2. Network detection ──────────────────────────────────────────────────────
# Network address of an "a.b.c.d/nn" address, e.g. 192.168.1.23/24 → 192.168.1.0/24
network_of() {
    local ip="${1%/*}" bits="${1#*/}" a b c d n mask
    IFS=. read -r a b c d <<< "$ip"
    n=$(( (a << 24) | (b << 16) | (c << 8) | d ))
    mask=$(( bits == 0 ? 0 : (0xFFFFFFFF << (32 - bits)) & 0xFFFFFFFF ))
    n=$(( n & mask ))
    echo "$(( (n >> 24) & 255 )).$(( (n >> 16) & 255 )).$(( (n >> 8) & 255 )).$(( n & 255 ))/${bits}"
}

if [ -z "$IFACE" ] && command -v ip >/dev/null; then
    IFACE="$(ip -o -4 route show default 2>/dev/null | awk '{for (i=1;i<NF;i++) if ($i=="dev") {print $(i+1); exit}}')"
fi
if [ -z "$SUBNET" ] && [ -n "$IFACE" ] && command -v ip >/dev/null; then
    _addr="$(ip -o -4 addr show dev "$IFACE" 2>/dev/null | awk '{print $4; exit}')"
    [ -n "$_addr" ] && SUBNET="$(network_of "$_addr")"
fi
if [ -n "$IFACE" ]; then ok "LAN interface: $IFACE"; else warn "Could not detect the LAN interface — set SNIFF_IFACE in .env"; IFACE=eth0; fi
if [ -n "$SUBNET" ]; then ok "LAN subnet: $SUBNET"; else warn "Could not detect the LAN subnet — set LAN_SUBNET in .env"; fi

# ── 3. .env ───────────────────────────────────────────────────────────────────
if [ -f .env ]; then
    info ".env already exists — leaving it unchanged"
else
    TIER="${TIER:-minimal}"
    case "$TIER" in
        minimal) PROFILES="" ;;
        *)       PROFILES="$TIER" ;;
    esac
    cat > .env <<EOF
# Heimdall — generated by setup.sh for this machine. Secrets live in secrets/.

# minimal | intermediate | full. COMPOSE_PROFILES must match, so a plain
# 'docker compose up -d' starts the right containers.
DEPLOYMENT_TIER=${TIER}
COMPOSE_PROFILES=${PROFILES}

# Pre-built images published by the GitHub release workflow.
HEIMDALL_REGISTRY=${REGISTRY}
IMAGE_TAG=${IMAGE_TAG}

# Read by docker compose to build DATABASE_URL for the backend.
DB_PASS=$(tr -d '[:space:]' < secrets/db_pass.txt)

# LAN-facing interface and subnet (check with: ip -4 addr).
SNIFF_IFACE=${IFACE}
LAN_SUBNET=${SUBNET:-10.100.102.0/24}
EOF
    chmod 600 .env
    ok "Created .env (tier: ${TIER})"
fi

# ── Next steps ────────────────────────────────────────────────────────────────
echo ""
case "$ROUTER" in
    sagemcom)
        info "Sagemcom router: put its admin password in ${B}secrets/router_password.txt${N} (or set it later on the Settings page)." ;;
    passive)
        warn "Passive mode (no router API) isn't available in this release yet. Heimdall starts with the Sagemcom adapter; pick your router on the Equipment page." ;;
    *)
        info "Pick your router on the Equipment page of the dashboard." ;;
esac
info "Dashboard login: user ${B}admin${N}, password in ${B}secrets/admin_password.txt${N}"
