// Writes src/styles/tokens.css from the product's frontend/src/index.css so the
// site's palettes cannot drift from the dashboard's. The site's own role names
// (primary/info/warn/crit) are aliases for the product's accent-* tokens.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(resolve(here, '../../frontend/src/index.css'), 'utf8');

function block(opener) {
  const start = css.indexOf(opener);
  if (start < 0) throw new Error(`gen-tokens: "${opener}" not found in frontend/src/index.css`);
  const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('}', start));
  const vars = {};
  for (const m of body.matchAll(/--color-([a-z0-9-]+):\s*([^;]+);/g)) vars[m[1]] = m[2].trim();
  return vars;
}

const palettes = {
  amber: block('@theme {'),
  slate: block(":root[data-palette='slate']"),
};
for (const [name, v] of Object.entries(palettes)) {
  for (const k of ['bg', 'surface', 'surface-elevated', 'border', 'border-active', 'accent-green', 'accent-blue', 'accent-amber', 'accent-red', 'text-primary', 'text-secondary', 'text-muted']) {
    if (!v[k]) throw new Error(`gen-tokens: palette ${name} lacks --color-${k}`);
  }
}

// The product's slate muted text is 4.2:1 on elevated surfaces; the site lifts it
// (docs/website/mockups/README.md). Everything else is copied unchanged.
const siteOverrides = { slate: { 'text-muted': '#8095b2' } };

const emit = (selector, v, name) => {
  const o = { ...v, ...(siteOverrides[name] || {}) };
  return `${selector} {
  --bg: ${o.bg}; --surface: ${o.surface}; --surface-2: ${o['surface-elevated']};
  --border: ${o.border}; --border-hi: ${o['border-active']};
  --primary: ${o['accent-green']}; --info: ${o['accent-blue']}; --warn: ${o['accent-amber']}; --crit: ${o['accent-red']};
  --text: ${o['text-primary']}; --text-2: ${o['text-secondary']}; --text-3: ${o['text-muted']};
  --on-primary: ${o.bg};
}
`;
};

const out = `/* GENERATED by scripts/gen-tokens.mjs from frontend/src/index.css. Do not edit. */
${emit(":root, :root[data-palette='amber']", palettes.amber, 'amber')}${emit(":root[data-palette='slate']", palettes.slate, 'slate')}`;
mkdirSync(resolve(here, '../src/styles'), { recursive: true });
writeFileSync(resolve(here, '../src/styles/tokens.css'), out);
console.log('gen-tokens: wrote src/styles/tokens.css');
